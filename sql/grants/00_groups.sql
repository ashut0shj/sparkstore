-- Unity Catalog / account-level groups (capstone requirement 65).
-- Groups are created at the ACCOUNT level (Databricks account console or
-- SCIM), not inside a notebook -- this file documents the exact group
-- names this project's grants depend on; run the equivalent steps in
-- docs/UNITY_CATALOG_AND_PERMISSIONS.md's manual UI walkthrough, or via
-- the Databricks CLI:
--
--   databricks account groups create --display-name maven_platform_admins
--   databricks account groups create --display-name maven_data_engineers
--   ... (repeat for each group below)
--   databricks account groups add-member <group-id> --user-id <user-id>
--
-- Verify every group actually exists before running 01_catalog_grants.sql
-- -- a GRANT to a group that doesn't exist fails loudly, which is the
-- correct, safe behavior (no silent no-op).

